// PG02 draft registration tests: no browser, no network, no mock business data.
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import vm from "node:vm";
import ts from "typescript";
const source=await readFile(new URL("../src/lib/client/draft-navigation.ts",import.meta.url),"utf8");
const script=ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;
const exports={};
vm.runInNewContext(script,{exports},{timeout:5000});
const {registerDraft,activeDrafts,saveActiveDrafts,discardActiveDrafts}=exports;
assert.equal(activeDrafts().length,0);
let dirty=true,discarded=0,saved=0;
const off=registerDraft({id:"payment-request-draft",isDirty:()=>dirty,save:async()=>{saved++;dirty=false;return true;},discard:()=>{discarded++;dirty=false;}});
assert.equal(activeDrafts().length,1);
assert.equal(await saveActiveDrafts(),true);
assert.equal(saved,1);
assert.equal(activeDrafts().length,0);
dirty=true;
assert.equal(discardActiveDrafts(),true);
assert.equal(discarded,1);
dirty=true;
let failedDirty=true;
const offFail=registerDraft({id:"unavailable-draft-save",isDirty:()=>failedDirty,save:async()=>false,discard:()=>{failedDirty=false;}});
assert.equal(await saveActiveDrafts(),false,"Failed save cannot allow navigation");
assert.equal(activeDrafts().length,1,"The saved draft is clean but failed draft stays dirty");
assert.equal(discardActiveDrafts(),true);
offFail();off();
assert.equal(activeDrafts().length,0,"Unmount cleanup must remove registration");
console.log("PG02 PASS: dirty guard, save-success, save-failure-stays, explicit discard, registration cleanup");

let deferredDirty=true;let applyDiscard;
const offDeferred=registerDraft({id:"react-deferred-discard",isDirty:()=>deferredDirty,save:async()=>false,discard:()=>{applyDiscard=()=>{deferredDirty=false}}});
assert.equal(discardActiveDrafts(),true,"React setState must not need a second discard click");
applyDiscard();assert.equal(activeDrafts().length,0);offDeferred();
const offThrow=registerDraft({id:"failed-discard",isDirty:()=>true,save:async()=>false,discard:()=>{throw Error("storage failure")}});
assert.equal(discardActiveDrafts(),false,"A thrown discard must still block navigation");offThrow();

let pendingSaved=true;let applySave;
const offSaved=registerDraft({id:"react-deferred-save",isDirty:()=>pendingSaved,save:async()=>{applySave=()=>{pendingSaved=false};return true},discard:()=>{pendingSaved=false}});
assert.equal(await saveActiveDrafts(),true,"Successful save must not fail while React state is pending");applySave();offSaved();
